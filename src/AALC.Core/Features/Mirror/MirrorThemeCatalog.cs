    private static readonly (string Alias, ThemePackDefinition Pack)[] Aliases = All
        .SelectMany(pack => pack.OcrAliases.Select(alias => (Alias: Normalize(alias), Pack: pack)))
        .OrderByDescending(entry => entry.Alias.Length).ThenBy(entry => entry.Pack.Id, StringComparer.Ordinal).ToArray();

    public static ThemePackDefinition? Match(string text)
    {
        var normalized = Normalize(text);
        foreach (var entry in Aliases)
            if (normalized.Contains(entry.Alias, StringComparison.Ordinal)) return entry.Pack;
        return null;
    }

    private static string Normalize(string text) => string.Concat(text.Where(c => !char.IsWhiteSpace(c))).ToUpperInvariant();
